// Turns a bulk vocabulary export into the shipped base-vocabulary module (words-data.js).
//
//   node tools/import-words.mjs "<path to the export>" [--out words-data.js]
//
// The export may hold several JSON arrays one after another (one per generated batch) with optional
// text between them, which is what a long chat session produces. Every row is validated with the
// app's own createWord(), so nothing that the app would refuse can reach the bundle. A spelling is
// unique across the whole vocabulary (the app's own rule — an imported word never shadows a shipped
// one), so a second entry for the same word is dropped even when its part of speech differs. Rows
// keep their source order, so appending more batches later never renumbers the words already shipped.
import {readFile, writeFile} from 'node:fs/promises';
import {createWord, normalizeWord} from '../vocabulary.js';
import {curatedWords} from '../words.js';

const LEVELS = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2'];

/** Every JSON array found in the text, concatenated. Throws if a block is not valid JSON. */
export function parseBlocks(text) {
  const rows = [];
  let depth = 0, start = -1;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === '"') { // skip over strings so brackets inside them are ignored
      i++;
      while (i < text.length && text[i] !== '"') i += text[i] === '\\' ? 2 : 1;
      continue;
    }
    if (c === '[') { if (depth === 0) start = i; depth++; }
    else if (c === ']') {
      depth--;
      if (depth === 0) {
        const block = text.slice(start, i + 1);
        const parsed = JSON.parse(block);
        if (Array.isArray(parsed)) rows.push(...parsed);
      }
      if (depth < 0) throw Error(`Unbalanced "]" at position ${i}.`);
    }
  }
  if (depth !== 0) throw Error('Unbalanced "[" — a block is not closed.');
  return rows;
}

/** Valid, de-duplicated rows in source order, as the compact arrays words-data.js ships. */
export function buildRows(input, existing = curatedWords) {
  const seen = new Set(existing.map(w => normalizeWord(w.word)));
  const out = [], skipped = {invalid: 0, duplicate: 0};
  for (const row of input) {
    let word;
    try { word = createWord(row); } catch { skipped.invalid++; continue; }
    if (!LEVELS.includes(word.level)) { skipped.invalid++; continue; }
    const key = normalizeWord(word.word);
    if (seen.has(key)) { skipped.duplicate++; continue; }
    seen.add(key);
    out.push([word.word, word.translation, word.ipa, word.pos, word.level, word.example,
      word.exampleMn, word.synonyms, word.antonyms, word.usage, word.usageMn]);
  }
  return {rows: out, skipped};
}

export function renderModule(rows) {
  const counts = {};
  for (const r of rows) counts[r[4]] = (counts[r[4]] || 0) + 1;
  const summary = LEVELS.filter(l => counts[l]).map(l => `${l} ${counts[l]}`).join(', ');
  return `// Base vocabulary. Generated by tools/import-words.mjs — do not edit by hand.\n`
    + `// ${rows.length} entries (${summary}). Columns: word, translation, ipa, pos, level, example,\n`
    + `// exampleMn, synonyms, antonyms, usage, usageMn. Stored as one JSON string: it parses faster\n`
    + `// than the same data written as JavaScript literals and keeps the diff to a single line.\n`
    + `export const extraRows = JSON.parse(${JSON.stringify(JSON.stringify(rows))});\n`;
}

if (process.argv[1]?.endsWith('import-words.mjs')) {
  const source = process.argv[2];
  if (!source) { console.error('Usage: node tools/import-words.mjs "<export file>" [--out words-data.js]'); process.exit(1); }
  const outIndex = process.argv.indexOf('--out');
  const out = outIndex === -1 ? 'words-data.js' : process.argv[outIndex + 1];
  const input = parseBlocks(await readFile(source, 'utf8'));
  const {rows, skipped} = buildRows(input);
  await writeFile(out, renderModule(rows), 'utf8');
  console.log(`${input.length} rows read → ${rows.length} written to ${out} `
    + `(${skipped.duplicate} duplicates, ${skipped.invalid} invalid).`);
}
