// Regenerates icons.js from the local Tabler SVG subset in assets/tabler.
// Source: @tabler/icons 3.31.0 (MIT, see assets/tabler/LICENSE). Run: node tools/icons.mjs
import {readdir,readFile,writeFile} from 'node:fs/promises';
const dir=new URL('../assets/tabler/',import.meta.url),out={};
for(const file of (await readdir(dir)).filter(f=>f.endsWith('.svg')).sort()){
 const svg=await readFile(new URL(file,dir),'utf8');
 const body=[...svg.matchAll(/<(path|circle|rect|line|polyline|ellipse)\b[^>]*\/>/g)].map(m=>m[0]).filter(s=>!s.includes('stroke="none"')).map(s=>s.replace(/\s+/g,' ').replace(' />','/>')).join('');
 out[file.slice(0,-4)]=body;
}
const src=`// Generated by tools/icons.mjs from official Tabler Icons 3.31.0 (MIT, assets/tabler/LICENSE). Do not edit by hand.
export const paths=${JSON.stringify(out)};
const aliases={book:'book-2',test:'checklist',chart:'chart-bar',review:'refresh',bookmark:'heart',arrow:'arrow-right',chevron:'chevron-right',stop:'player-stop',play:'player-play',practice:'target-arrow',progress:'chart-bar',grammar:'school',vocabulary:'book-2',collections:'folders',favorite:'heart',achievement:'trophy',notification:'bell',listening:'headphones',speaking:'microphone',writing:'pencil',statistics:'chart-bar'};
/** Tabler icon as inline SVG. Outline by default; {filled:true} uses the -filled variant when available. */
export function icon(name,{filled=false,size,label,className=''}={}){
 const key=aliases[name]||name,id=filled&&paths[key+'-filled']?key+'-filled':key,isFilled=id.endsWith('-filled');
 const a11y=label?\`role="img" aria-label="\${label}"\`:'aria-hidden="true"';
 return \`<svg class="ui-icon\${isFilled?' is-filled':''}\${className?' '+className:''}" viewBox="0 0 24 24" \${size?\`width="\${size}" height="\${size}" \`:''}fill="\${isFilled?'currentColor':'none'}" stroke="\${isFilled?'none':'currentColor'}" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" \${a11y} focusable="false">\${paths[id]||paths['circle-dot']}</svg>\`;
}
export const iconNames=Object.keys(paths);
`;
await writeFile(new URL('../icons.js',import.meta.url),src,'utf8');
console.log(`icons.js: ${Object.keys(out).length} icons`);
